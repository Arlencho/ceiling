import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export type VetoIdl = {
  programId: string;
  events: { paid: Buffer; refused: Buffer };
  ixs: { openMandate: Buffer; grantOverride: Buffer; charge: Buffer };
};

type IdlJson = {
  address?: string;
  metadata?: { address?: string };
  instructions?: { name: string; discriminator: number[] }[];
  events?: { name: string; discriminator: number[] }[];
};

export function defaultIdlPath(): string {
  const here = path.dirname(fileURLToPath(import.meta.url));
  return path.resolve(here, "../../../../indexer/idl/veto.json");
}

function discriminator(list: { name: string; discriminator: number[] }[], name: string): Buffer {
  const entry = list.find((e) => e.name === name);
  if (!entry) throw new Error(`IDL has no entry named ${name}`);
  if (entry.discriminator.length !== 8) {
    throw new Error(`IDL discriminator for ${name} is ${entry.discriminator.length} bytes, expected 8`);
  }
  return Buffer.from(entry.discriminator);
}

// Reads the program id and the Anchor discriminators straight from the IDL so
// the generated bytes track the deployed program instead of a copied constant.
export function loadVetoIdl(idlPath: string = defaultIdlPath()): VetoIdl {
  const idl = JSON.parse(readFileSync(idlPath, "utf8")) as IdlJson;
  const programId = idl.address ?? idl.metadata?.address;
  if (!programId) throw new Error(`IDL at ${idlPath} has no program address`);
  return {
    programId,
    events: {
      paid: discriminator(idl.events ?? [], "Paid"),
      refused: discriminator(idl.events ?? [], "Refused"),
    },
    ixs: {
      openMandate: discriminator(idl.instructions ?? [], "open_mandate"),
      grantOverride: discriminator(idl.instructions ?? [], "grant_override"),
      charge: discriminator(idl.instructions ?? [], "charge"),
    },
  };
}
